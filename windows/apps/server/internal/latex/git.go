// GitFileChange 描述 Git 工作区里单个变更文件。
type GitFileChange struct {
	Path           string `json:"path"`
	IndexStatus    string `json:"indexStatus"`
	WorktreeStatus string `json:"worktreeStatus"`
	Summary        string `json:"summary"`
}

// GitStatusReport 描述当前 LaTeX 项目的 Git 仓库状态。
type GitStatusReport struct {
	Available   bool            `json:"available"`
	Initialized bool            `json:"initialized"`
	Branch      string          `json:"branch"`
	RemoteURL   string          `json:"remoteUrl"`
	Clean       bool            `json:"clean"`
	Ahead       int             `json:"ahead"`
	Behind      int             `json:"behind"`
	LastCommit  string          `json:"lastCommit"`
	Changes     []GitFileChange `json:"changes"`
	Message     string          `json:"message,omitempty"`
}

// GitSyncResult 描述一次 commit/pull/push 同步操作的结果。
type GitSyncResult struct {
	Committed bool             `json:"committed"`
	Pulled    bool             `json:"pulled"`
	Pushed    bool             `json:"pushed"`
	Branch    string           `json:"branch"`
	Output    string           `json:"output"`
	Status    *GitStatusReport `json:"status"`
}

var (
	// ErrGitUnavailable 表示本机未安装 git CLI。
	ErrGitUnavailable = errors.New("当前环境未检测到 git 命令，请先安装 Git")
	// ErrGitInvalidInput 表示 Git 提交信息或远程仓库地址不合法。
	ErrGitInvalidInput = errors.New("Git 参数无效")
)

var scpRemotePattern = regexp.MustCompile(`^[A-Za-z0-9._-]+@[A-Za-z0-9.-]+:[A-Za-z0-9._/@-]+$`)

const defaultLatexGitignore = `# LaTeX build artifacts generated by ReadX or local TeX engines
*.aux
*.bbl
*.bcf
*.blg
*.fdb_latexmk
*.fls
*.idx
*.ilg
*.ind
*.lof
*.log
*.lot
*.nav
*.out
*.run.xml
*.snm
*.synctex.gz
*.toc
*.xdv
.readx-build/
`

// GitStatus 检查 LaTeX 项目源码目录的 Git 状态。
func (s *Service) GitStatus(ctx context.Context, projectID string) (*GitStatusReport, error) {
	if _, err := s.Get(ctx, projectID); err != nil {
		return nil, err
	}
	srcDir, err := s.SrcDir(projectID)
	if err != nil {
		return nil, err
	}
	return s.inspectGitStatus(ctx, srcDir)
}

func (s *Service) inspectGitStatus(ctx context.Context, srcDir string) (*GitStatusReport, error) {
	report := &GitStatusReport{Changes: []GitFileChange{}}
	gitPath, err := exec.LookPath("git")
	if err != nil {
		report.Available = false
		report.Message = ErrGitUnavailable.Error()
		return report, nil
	}
	report.Available = true

	if _, statErr := os.Stat(filepath.Join(srcDir, ".git")); statErr != nil {
		report.Initialized = false
		report.Clean = true
		return report, nil
	}
	report.Initialized = true

	if branch, _, branchErr := runGitCommand(ctx, gitPath, srcDir, 5*time.Second, "rev-parse", "--abbrev-ref", "HEAD"); branchErr == nil {
		branch = strings.TrimSpace(branch)
		if branch != "" && branch != "HEAD" {
			report.Branch = branch
		}
	}
	if report.Branch == "" {
		if sym, _, symErr := runGitCommand(ctx, gitPath, srcDir, 5*time.Second, "symbolic-ref", "--short", "HEAD"); symErr == nil {
			report.Branch = strings.TrimSpace(sym)
		}
	}

	if remote, _, remoteErr := runGitCommand(ctx, gitPath, srcDir, 5*time.Second, "remote", "get-url", "origin"); remoteErr == nil {
		report.RemoteURL = strings.TrimSpace(remote)
	}

	if logOut, _, logErr := runGitCommand(ctx, gitPath, srcDir, 5*time.Second, "log", "-1", "--pretty=format:%h %s (%cr)"); logErr == nil {
		report.LastCommit = strings.TrimSpace(logOut)
	}

	statusOut, stderr, statusErr := runGitCommand(ctx, gitPath, srcDir, 5*time.Second, "status", "--porcelain=v1", "-b")
	if statusErr != nil {
		return nil, fmt.Errorf("读取 Git 状态失败: %s (%w)", strings.TrimSpace(stderr), statusErr)
	}

	for _, line := range strings.Split(strings.ReplaceAll(statusOut, "\r\n", "\n"), "\n") {
		if line == "" {
			continue
		}
		if strings.HasPrefix(line, "## ") {
			ahead, behind, parsedBranch := parseGitBranchHeader(line[3:])
			report.Ahead = ahead
			report.Behind = behind
			if report.Branch == "" && parsedBranch != "" {
				report.Branch = parsedBranch
			}
			continue
		}
		if len(line) < 4 {
			continue
		}
		idx := line[0:1]
		wt := line[1:2]
		pathPart := strings.TrimSpace(line[3:])
		report.Changes = append(report.Changes, GitFileChange{
			Path:           pathPart,
			IndexStatus:    idx,
			WorktreeStatus: wt,
			Summary:        summarizeGitChange(idx, wt),
		})
	}
	report.Clean = len(report.Changes) == 0
	return report, nil
}

// GitInit 在 LaTeX 项目源码目录初始化 Git 仓库并生成默认 .gitignore。
func (s *Service) GitInit(ctx context.Context, projectID, defaultBranch string) (*GitStatusReport, error) {
	if _, err := s.Get(ctx, projectID); err != nil {
		return nil, err
	}
	srcDir, err := s.SrcDir(projectID)
	if err != nil {
		return nil, err
	}
	gitPath, err := exec.LookPath("git")
	if err != nil {
		return nil, ErrGitUnavailable
	}
	branch := sanitizeGitBranchName(defaultBranch)
	if _, statErr := os.Stat(filepath.Join(srcDir, ".git")); statErr != nil {
		if _, stderr, initErr := runGitCommand(ctx, gitPath, srcDir, 8*time.Second, "init", "-b", branch); initErr != nil {
			// Fallback for older Git versions without -b.
			if _, stderr2, fallbackErr := runGitCommand(ctx, gitPath, srcDir, 8*time.Second, "init"); fallbackErr != nil {
				return nil, fmt.Errorf("初始化 Git 仓库失败: %s (%w)", strings.TrimSpace(stderr+" "+stderr2), fallbackErr)
			}
			_, _, _ = runGitCommand(ctx, gitPath, srcDir, 5*time.Second, "checkout", "-B", branch)
		}
	}
	gitignorePath := filepath.Join(srcDir, ".gitignore")
	if _, statErr := os.Stat(gitignorePath); os.IsNotExist(statErr) {
		_ = os.WriteFile(gitignorePath, []byte(defaultLatexGitignore), 0o644)
	}
	return s.inspectGitStatus(ctx, srcDir)
}

// GitCommit 暂存并提交项目中的源码更改。
func (s *Service) GitCommit(ctx context.Context, projectID, message string) (*GitStatusReport, error) {
	msg := strings.TrimSpace(message)
	if msg == "" {
		return nil, fmt.Errorf("%w: 提交说明不能为空", ErrGitInvalidInput)
	}
	if len(msg) > 500 || strings.ContainsAny(msg, "\r\n\x00") {
		return nil, fmt.Errorf("%w: 提交说明不能包含换行且长度不超过 500 字", ErrGitInvalidInput)
	}
	if _, err := s.Get(ctx, projectID); err != nil {
		return nil, err
	}
	srcDir, err := s.SrcDir(projectID)
	if err != nil {
		return nil, err
	}
	gitPath, err := exec.LookPath("git")
	if err != nil {
		return nil, ErrGitUnavailable
	}
	if _, statErr := os.Stat(filepath.Join(srcDir, ".git")); statErr != nil {
		if _, initErr := s.GitInit(ctx, projectID, "main"); initErr != nil {
			return nil, initErr
		}
	}
	if _, stderr, addErr := runGitCommand(ctx, gitPath, srcDir, 10*time.Second, "add", "-A"); addErr != nil {
		return nil, fmt.Errorf("暂存文件失败: %s (%w)", strings.TrimSpace(stderr), addErr)
	}
	if _, _, diffErr := runGitCommand(ctx, gitPath, srcDir, 5*time.Second, "diff", "--cached", "--quiet"); diffErr == nil {
		return nil, fmt.Errorf("%w: 工作区没有新的更改需要提交", ErrGitInvalidInput)
	}
	commitArgs := commitArgsWithFallbackAuthor(ctx, gitPath, srcDir, msg)
	if _, stderr, commitErr := runGitCommand(ctx, gitPath, srcDir, 10*time.Second, commitArgs...); commitErr != nil {
		return nil, fmt.Errorf("提交失败: %s (%w)", strings.TrimSpace(stderr), commitErr)
	}
	return s.inspectGitStatus(ctx, srcDir)
}

// GitSetRemote 校验并设置 origin 远程仓库地址。
func (s *Service) GitSetRemote(ctx context.Context, projectID, remoteURL string) (*GitStatusReport, error) {
	cleanURL, err := validateGitRemoteURL(remoteURL)
	if err != nil {
		return nil, err
	}
	if _, err := s.Get(ctx, projectID); err != nil {
		return nil, err
	}
	srcDir, err := s.SrcDir(projectID)
	if err != nil {
		return nil, err
	}
	gitPath, err := exec.LookPath("git")
	if err != nil {
		return nil, ErrGitUnavailable
	}
	if _, statErr := os.Stat(filepath.Join(srcDir, ".git")); statErr != nil {
		if _, initErr := s.GitInit(ctx, projectID, "main"); initErr != nil {
			return nil, initErr
		}
	}
	if _, _, getErr := runGitCommand(ctx, gitPath, srcDir, 5*time.Second, "remote", "get-url", "origin"); getErr == nil {
		if _, stderr, setErr := runGitCommand(ctx, gitPath, srcDir, 5*time.Second, "remote", "set-url", "origin", "--", cleanURL); setErr != nil {
			return nil, fmt.Errorf("更新远程仓库失败: %s (%w)", strings.TrimSpace(stderr), setErr)
		}
	} else {
		if _, stderr, addErr := runGitCommand(ctx, gitPath, srcDir, 5*time.Second, "remote", "add", "origin", "--", cleanURL); addErr != nil {
			return nil, fmt.Errorf("添加远程仓库失败: %s (%w)", strings.TrimSpace(stderr), addErr)
		}
	}
	return s.inspectGitStatus(ctx, srcDir)
}

// GitSync 执行拉取/推送（在传入提交信息且有未提交更改时先自动提交）。
func (s *Service) GitSync(ctx context.Context, projectID, mode, commitMessage string) (*GitSyncResult, error) {
	mode = strings.ToLower(strings.TrimSpace(mode))
	if mode == "" {
		mode = "both"
	}
	if mode != "pull" && mode != "push" && mode != "both" {
		return nil, fmt.Errorf("%w: mode 仅支持 pull / push / both", ErrGitInvalidInput)
	}
	status, err := s.GitStatus(ctx, projectID)
	if err != nil {
		return nil, err
	}
	if !status.Available {
		return nil, ErrGitUnavailable
	}
	if !status.Initialized {
		return nil, fmt.Errorf("%w: 请先初始化 Git 仓库", ErrGitInvalidInput)
	}
	if status.RemoteURL == "" {
		return nil, fmt.Errorf("%w: 尚未配置远程仓库 origin", ErrGitInvalidInput)
	}

	srcDir, err := s.SrcDir(projectID)
	if err != nil {
		return nil, err
	}
	gitPath, err := exec.LookPath("git")
	if err != nil {
		return nil, ErrGitUnavailable
	}

	res := &GitSyncResult{Branch: status.Branch}
	var outputs []string

	if !status.Clean && strings.TrimSpace(commitMessage) != "" {
		updated, commitErr := s.GitCommit(ctx, projectID, commitMessage)
		if commitErr != nil {
			return nil, commitErr
		}
		res.Committed = true
		status = updated
	}
	branch := status.Branch
	if branch == "" {
		branch = "main"
		res.Branch = branch
	}

	if mode == "pull" || mode == "both" {
		// Check if remote branch exists before pulling so freshly created empty remotes don't error out unexpectedly.
		lsOut, _, lsErr := runGitCommand(ctx, gitPath, srcDir, 15*time.Second, "ls-remote", "--heads", "origin", branch)
		if lsErr != nil {
			return nil, fmt.Errorf("连接远程仓库失败: %w", lsErr)
		}
		if strings.TrimSpace(lsOut) != "" {
			out, stderr, pullErr := runGitCommand(ctx, gitPath, srcDir, 30*time.Second, "pull", "--rebase", "--autostash", "origin", branch)
			combined := strings.TrimSpace(out + "\n" + stderr)
			if pullErr != nil {
				return nil, fmt.Errorf("Git 拉取失败: %s (%w)", combined, pullErr)
			}
			if combined != "" {
				outputs = append(outputs, combined)
			}
			res.Pulled = true
		} else {
			outputs = append(outputs, "远端暂无分支 "+branch+"，已跳过拉取。")
		}
	}

	if mode == "push" || mode == "both" {
		if status.LastCommit == "" && !res.Committed {
			return nil, fmt.Errorf("%w: 本地还没有任何提交，请先提交后再推送", ErrGitInvalidInput)
		}
		out, stderr, pushErr := runGitCommand(ctx, gitPath, srcDir, 30*time.Second, "push", "-u", "origin", branch)
		combined := strings.TrimSpace(out + "\n" + stderr)
		if pushErr != nil {
			return nil, fmt.Errorf("Git 推送失败: %s (%w)", combined, pushErr)
		}
		if combined != "" {
			outputs = append(outputs, combined)
		}
		res.Pushed = true
	}

	finalStatus, err := s.inspectGitStatus(ctx, srcDir)
	if err != nil {
		return nil, err
	}
	res.Status = finalStatus
	res.Output = strings.Join(outputs, "\n")
	return res, nil
}

func validateGitRemoteURL(raw string) (string, error) {
	trimmed := strings.TrimSpace(raw)
	if trimmed == "" {
		return "", fmt.Errorf("%w: 远程仓库地址不能为空", ErrGitInvalidInput)
	}
	if strings.HasPrefix(trimmed, "-") || strings.ContainsAny(trimmed, " \t\r\n\x00") {
		return "", fmt.Errorf("%w: 远程仓库地址包含非法字符", ErrGitInvalidInput)
	}
	if scpRemotePattern.MatchString(trimmed) {
		return trimmed, nil
	}
	parsed, err := url.Parse(trimmed)
	if err != nil || parsed.Host == "" {
		return "", fmt.Errorf("%w: 仅支持 https://、http://、ssh:// 或 git@host:path 格式的远程仓库", ErrGitInvalidInput)
	}
	switch strings.ToLower(parsed.Scheme) {
	case "https", "http", "ssh":
		return trimmed, nil
	default:
		return "", fmt.Errorf("%w: 不支持的协议 %q，仅支持 https/http/ssh/git@", ErrGitInvalidInput, parsed.Scheme)
	}
}

func sanitizeGitBranchName(raw string) string {
	branch := strings.TrimSpace(raw)
	if branch == "" || strings.HasPrefix(branch, "-") || strings.ContainsAny(branch, " \t\r\n\x00..") {
		return "main"
	}
	return branch
}

func commitArgsWithFallbackAuthor(ctx context.Context, gitPath, srcDir, msg string) []string {
	nameOut, _, _ := runGitCommand(ctx, gitPath, srcDir, 3*time.Second, "config", "user.name")
	emailOut, _, _ := runGitCommand(ctx, gitPath, srcDir, 3*time.Second, "config", "user.email")
	args := make([]string, 0, 8)
	if strings.TrimSpace(nameOut) == "" {
		args = append(args, "-c", "user.name=ReadX")
	}
	if strings.TrimSpace(emailOut) == "" {
		args = append(args, "-c", "user.email=readx@local")
	}
	args = append(args, "commit", "-m", msg)
	return args
}

func runGitCommand(ctx context.Context, gitPath, dir string, timeout time.Duration, args ...string) (string, string, error) {
	runCtx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()
	cmd := exec.CommandContext(runCtx, gitPath, args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GIT_TERMINAL_PROMPT=0", "LC_ALL=C")
	var stdout, stderr bytes.Buffer
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr
	err := cmd.Run()
	return stdout.String(), stderr.String(), err
}

func parseGitBranchHeader(header string) (ahead, behind int, branch string) {
	mainPart := header
	if idx := strings.Index(header, "..."); idx >= 0 {
		branch = strings.TrimSpace(header[:idx])
		mainPart = header[idx+3:]
	} else {
		branch = strings.TrimSpace(strings.TrimPrefix(header, "No commits yet on "))
	}
	if l := strings.Index(mainPart, "["); l >= 0 {
		if r := strings.Index(mainPart[l:], "]"); r > 0 {
			meta := mainPart[l+1 : l+r]
			for _, part := range strings.Split(meta, ",") {
				p := strings.TrimSpace(part)
				if strings.HasPrefix(p, "ahead ") {
					ahead, _ = strconv.Atoi(strings.TrimPrefix(p, "ahead "))
				} else if strings.HasPrefix(p, "behind ") {
					behind, _ = strconv.Atoi(strings.TrimPrefix(p, "behind "))
				}
			}
		}
	}
	return ahead, behind, branch
}

func summarizeGitChange(idx, wt string) string {
	switch idx + wt {
	case "??":
		return "未跟踪"
	case "A ", "AM":
		return "新增"
	case " M", "M ", "MM":
		return "已修改"
	case " D", "D ":
		return "已删除"
	case "R ", "RM":
		return "重命名"
	default:
		if idx == "U" || wt == "U" {
			return "存在冲突"
		}
		return "已变更"
	}
}
